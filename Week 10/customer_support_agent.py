def test_contextual_response():
    agent = CustomerSupportAgent()

    agent.generate_response(
        "My name is Rahul and my delivery is late"
    )

    response = agent.generate_response(
        "My order is ORD555"
    )

    assert "Rahul" in response
    assert "ORD555" in response

    print("PASS: Contextual response")


